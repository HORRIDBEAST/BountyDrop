#!/usr/bin/env node
// scripts/gen-abi.mjs
//
// Regenerates lib/abi.ts from Foundry build artifacts. Run this after
// `forge build` inside contracts/ (or after `forge script ... --broadcast`,
// which builds first). No @wagmi/cli codegen is used, mirroring MicroWorks'
// approach — see BOUNTYDROP_MASTER_SPEC.md Section 1.
//
// Usage (from repo root):
//   cd contracts && forge build && cd ..
//   npm run gen-abi

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const CONTRACTS = [
  { name: "QuestEscrow", artifact: "contracts/out/QuestEscrow.sol/QuestEscrow.json" },
  { name: "SpendVault", artifact: "contracts/out/SpendVault.sol/SpendVault.json" },
];

const OUTPUT_PATH = "lib/abi.ts";

function loadAbi(artifactPath) {
  if (!existsSync(artifactPath)) {
    throw new Error(
      `Missing Foundry artifact at ${artifactPath}. Run "cd contracts && forge build" first.`,
    );
  }
  const json = JSON.parse(readFileSync(artifactPath, "utf8"));
  return json.abi;
}

function main() {
  const exports = [];
  for (const { name, artifact } of CONTRACTS) {
    const abi = loadAbi(join(process.cwd(), artifact));
    exports.push(`export const ${name.toUpperCase()}_ABI = ${JSON.stringify(abi, null, 2)} as const;`);
  }

  const header = `// lib/abi.ts
//
// GENERATED BY scripts/gen-abi.mjs FROM FOUNDRY BUILD ARTIFACTS.
// DO NOT EDIT BY HAND — re-run \`npm run gen-abi\` after any contract change.
// See BOUNTYDROP_MASTER_SPEC.md Section 1 for why this project generates
// the ABI from Foundry output instead of hand-writing or wagmi-cli-codegen.
`;

  writeFileSync(OUTPUT_PATH, `${header}\n${exports.join("\n\n")}\n`);
  console.log(`Wrote ${OUTPUT_PATH} from ${CONTRACTS.length} Foundry artifact(s).`);
}

main();
